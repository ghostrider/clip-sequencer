#!/usr/bin/env node
// Builds the project site into site/dist/ (M11 Phase G2): the landing pages (site/landing/) at the root and the
// user manual (mdBook, site/manual/) under manual/. Runs on Windows and Linux (CI); needs Node and mdbook.
//
//   node site/build.mjs            development build (placeholders allowed, warns about them)
//   node site/build.mjs --release  for publishing: fails if the contact address is not set in site/site.json
//
// Steps: copy the app's tokens and IBM Plex fonts into site/shared/ and the manual theme; generate the
// keyboard-shortcuts page from web/src/lib/shortcuts.json (the app's own list); run mdbook (warnings fail the
// build); add the "Manual for version x.y.z" footer ([workspace.package] version); fill the landing pages'
// placeholders; check that every internal link resolves and that no page loads anything from another host.

import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = dirname(fileURLToPath(import.meta.url));
const root = join(site, '..');
const dist = join(site, 'dist');
const release = process.argv.includes('--release');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n');
const problems = [];
const warn = (m) => console.warn(`site: warning: ${m}`);

const version = /\[workspace\.package\][^[]*?\nversion = "([^"]+)"/.exec(read('Cargo.toml'))?.[1];
if (!version) throw new Error('no version in [workspace.package] of Cargo.toml');
const config = JSON.parse(read('site/site.json'));

// ---- shared assets: tokens and fonts (one source: the app) --------------------------------------------
const fontsSrc = join(root, 'crates/seq-app/shell/fonts');
const fonts = readdirSync(fontsSrc).filter((f) => f.endsWith('.woff2'));
const fontFace = (f, url) => {
  const m = /ibm-plex-(sans|mono)-latin-(\d+)-normal\.woff2/.exec(f);
  if (!m) throw new Error(`unexpected font file ${f}`);
  const family = `IBM Plex ${m[1] === 'sans' ? 'Sans' : 'Mono'}`;
  return `@font-face { font-family: '${family}'; font-style: normal; font-weight: ${m[2]}; font-display: swap; src: url(${url}${f}) format('woff2'); }\n`;
};
rmSync(join(site, 'shared'), { recursive: true, force: true });
mkdirSync(join(site, 'shared/fonts'), { recursive: true });
cpSync(join(root, 'web/src/tokens.css'), join(site, 'shared/tokens.css'));
for (const f of [...fonts, 'OFL.txt']) cpSync(join(fontsSrc, f), join(site, 'shared/fonts', f));
writeFileSync(join(site, 'shared/fonts.css'), fonts.map((f) => fontFace(f, 'fonts/')).join(''));
cpSync(join(root, 'web/public/favicon.png'), join(site, 'shared/favicon.png'));
cpSync(join(root, 'web/public/icon.png'), join(site, 'shared/icon.png'));

// mdBook replaces its own fonts when the theme has fonts/fonts.css; the files land in manual/fonts/.
const themeFonts = join(site, 'manual/theme/fonts');
rmSync(themeFonts, { recursive: true, force: true });
mkdirSync(themeFonts, { recursive: true });
for (const f of [...fonts, 'OFL.txt']) cpSync(join(fontsSrc, f), join(themeFonts, f));
writeFileSync(join(themeFonts, 'fonts.css'), fonts.map((f) => fontFace(f, '')).join(''));

// ---- keyboard shortcuts page, from the app's list ----------------------------------------------------
const groups = JSON.parse(read('web/src/lib/shortcuts.json'));
const where = { desktop: ' *(desktop app only)*', browser: ' *(browser UI only)*' };
let md = '# Keyboard shortcuts\n\n';
md += '<!-- Generated by site/build.mjs from web/src/lib/shortcuts.json, the list the app shows under Help → Keyboard shortcuts. Edit that file, not this page. -->\n\n';
md += 'The same list is in the app under **Help → Keyboard shortcuts**.\n\n';
for (const g of groups) {
  md += `## ${g.title}\n\n| Keys | Action |\n|---|---|\n`;
  for (const s of g.items) md += `| <kbd>${s.keys.replace(/\|/g, '\\|')}</kbd> | ${s.what}${s.only ? where[s.only] : ''} |\n`;
  md += '\n';
}
writeFileSync(join(site, 'manual/src/keyboard-shortcuts.md'), md);

// ---- manual -------------------------------------------------------------------------------------------
rmSync(dist, { recursive: true, force: true });
const mdbook = spawnSync('mdbook', ['build', join(site, 'manual'), '--dest-dir', join(dist, 'manual')], {
  encoding: 'utf8',
  env: { ...process.env, NO_COLOR: '1' },
});
if (mdbook.error) throw new Error(`mdbook could not run (is it installed?): ${mdbook.error.message}`);
const mdlog = `${mdbook.stdout}${mdbook.stderr}`;
if (mdbook.status !== 0) throw new Error(`mdbook failed:\n${mdlog}`);
// Warnings (e.g. a chapter in SUMMARY.md without a file, a bad link in a chapter) fail the build.
for (const line of mdlog.split('\n')) if (/\b(WARN|ERROR)\b/.test(line)) problems.push(`mdbook: ${line.trim()}`);

const footer = `<footer class="manual-footer">Manual for version ${version} · <a href="https://github.com/ghostrider/clip-sequencer/releases">Releases</a> · <a href="../">Project site</a></footer>`;
for (const f of walk(join(dist, 'manual'))) {
  if (extname(f) !== '.html' || f.endsWith('print.html') || f.endsWith('toc.html')) continue;
  const html = readFileSync(f, 'utf8');
  if (!html.includes('</main>')) continue;
  writeFileSync(f, html.replace('</main>', `${footer}\n</main>`));
}

// ---- landing pages ------------------------------------------------------------------------------------
const values = {
  VERSION: version,
  BASE_URL: config.baseUrl,
  REPO: config.repository,
  OWNER: config.owner,
  CONTACT: config.contactEmail ?? 'contact address follows',
  CONTACT_HREF: config.contactEmail ? `mailto:${config.contactEmail}` : '#',
};
if (!config.contactEmail) {
  if (release) problems.push('site/site.json: contactEmail is required for a release build (legal notice)');
  else warn('contactEmail not set: the contact page shows a placeholder');
}
for (const f of walk(join(site, 'landing'))) {
  const out = join(dist, relative(join(site, 'landing'), f));
  mkdirSync(dirname(out), { recursive: true });
  if (extname(f) === '.html') {
    let html = readFileSync(f, 'utf8');
    // {{#SHOP}}…{{/SHOP}} only when a shop URL is configured (binaries are also sold, Phase A decision (c)).
    html = html.replace(/\{\{#SHOP\}\}([\s\S]*?)\{\{\/SHOP\}\}/g, (_, inner) => (config.shopUrl ? inner : ''));
    html = html.replace(/\{\{SHOP_URL\}\}/g, config.shopUrl ?? '');
    html = html.replace(/\{\{(\w+)\}\}/g, (m, k) => {
      if (!(k in values)) problems.push(`${relative(root, f)}: unknown placeholder ${m}`);
      return values[k] ?? m;
    });
    writeFileSync(out, html);
  } else cpSync(f, out);
}
cpSync(join(site, 'shared'), join(dist, 'shared'), { recursive: true });
cpSync(join(root, 'docs/images/screenshot.png'), join(dist, 'shared/screenshot.png'));

// ---- checks -------------------------------------------------------------------------------------------
const pages = walk(dist).filter((f) => extname(f) === '.html');
for (const page of pages) {
  const html = readFileSync(page, 'utf8');
  const rel = relative(dist, page);
  // Resources the browser fetches by itself must come from this site (no fonts, CDNs, analytics, embeds).
  for (const m of html.matchAll(/<(script|img|iframe|source|video|audio)\b[^>]*\bsrc="([^"]*)"/gi)) {
    if (/^(https?:)?\/\//i.test(m[2])) problems.push(`${rel}: loads ${m[2]} from another host`);
  }
  for (const m of html.matchAll(/<link\b[^>]*>/gi)) {
    const href = /\bhref="([^"]*)"/i.exec(m[0])?.[1] ?? '';
    const relAttr = /\brel="([^"]*)"/i.exec(m[0])?.[1] ?? '';
    if (/stylesheet|icon|preload|prefetch|manifest/i.test(relAttr) && /^(https?:)?\/\//i.test(href)) {
      problems.push(`${rel}: loads ${href} from another host`);
    }
  }
  // Internal links and resources must exist.
  for (const m of html.matchAll(/\b(?:href|src)="([^"]*)"/gi)) {
    const url = m[1];
    if (!url || /^(https?:|mailto:|#|data:|javascript:)/i.test(url) || url.startsWith('//')) continue;
    if (url.includes('{{')) continue; // mdBook's search template strings
    const path = decodeURI(url.split('#')[0].split('?')[0]);
    if (!path) continue;
    let target = path.startsWith('/') ? join(dist, path.replace(/^\/clip-sequencer\//, '/')) : resolve(dirname(page), path);
    if (existsSync(target) && statSync(target).isDirectory()) target = join(target, 'index.html');
    if (!existsSync(target)) problems.push(`${rel}: broken link ${url}`);
  }
}
for (const css of walk(dist).filter((f) => extname(f) === '.css')) {
  for (const m of readFileSync(css, 'utf8').matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/gi)) {
    const url = m[1].trim();
    if (/^(https?:)?\/\//i.test(url)) problems.push(`${relative(dist, css)}: loads ${url} from another host`);
    else if (!/^(data:|#)/i.test(url) && !existsSync(resolve(dirname(css), decodeURI(url.split(/[?#]/)[0])))) {
      problems.push(`${relative(dist, css)}: missing ${url}`);
    }
  }
}

if (problems.length) {
  for (const p of problems) console.error(`site: ${p}`);
  process.exit(1);
}
console.log(`site: built ${pages.length} pages into ${relative(root, dist)} (version ${version})`);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}
